const REFERENCE_KEYS = Object.keys(WORKBENCH_TRANSLATIONS.en).sort();
for (const locale of SUPPORTED_WORKBENCH_LOCALES) {
  const keys = Object.keys(WORKBENCH_TRANSLATIONS[locale] ?? {}).sort();
  if (keys.length !== REFERENCE_KEYS.length || keys.some((key, index) => key !== REFERENCE_KEYS[index])) {
    throw new Error(`workbench_i18n_catalog_mismatch:${locale}`);
  }
}

export function normalizeWorkbenchLocale(value) {
  const candidates = Array.isArray(value) ? value : [value];
  for (const candidate of candidates) {
    if (typeof candidate !== "string") continue;
    const normalized = candidate.trim().replaceAll("_", "-").toLowerCase();
    if (normalized === "zh" || normalized.startsWith("zh-")) return "zh-CN";
    if (normalized === "en" || normalized.startsWith("en-")) return "en";
  }
  return "en";
}

export function translateWorkbench(locale, key, vars = {}) {
  const normalizedLocale = normalizeWorkbenchLocale(locale);
  const catalog = WORKBENCH_TRANSLATIONS[normalizedLocale];
  const message = catalog[String(key)];
  if (message == null) throw new Error(`workbench_i18n_key_missing:${String(key)}`);
  if (!vars || typeof vars !== "object" || Array.isArray(vars)) {
    throw new Error("workbench_i18n_vars_invalid");
  }
  return message.replace(/\{([A-Za-z][A-Za-z0-9_]*)\}/g, (_match, variable) => {
    if (!Object.hasOwn(vars, variable)) throw new Error(`workbench_i18n_variable_missing:${variable}`);
    return String(vars[variable]);
  });
}

function deepFreeze(value) {
  if (!value || typeof value !== "object" || Object.isFrozen(value)) return value;
  for (const nested of Object.values(value)) deepFreeze(nested);
  return Object.freeze(value);
}
